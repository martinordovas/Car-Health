-- Car Health · esquema inicial
-- Compatible con PostgreSQL 16+ y H2 en modo PostgreSQL.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    email_verification_code_hash VARCHAR(100),
    email_verification_expires_at TIMESTAMP(6) WITH TIME ZONE,
    email_verification_sent_at TIMESTAMP(6) WITH TIME ZONE,
    email_verification_attempts INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    nickname VARCHAR(60),
    brand VARCHAR(60) NOT NULL,
    model VARCHAR(80) NOT NULL,
    model_year INTEGER NOT NULL,
    engine_code VARCHAR(40),
    vin VARCHAR(40),
    license_plate VARCHAR(20),
    current_odometer INTEGER NOT NULL DEFAULT 0,
    purchase_date DATE,
    purchase_price NUMERIC(12, 2),
    fuel_type VARCHAR(24) NOT NULL DEFAULT 'GASOLINE_95',
    color VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_vehicles_user ON vehicles (user_id);

CREATE TABLE fuel_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    fuel_date TIMESTAMP NOT NULL,
    odometer INTEGER NOT NULL,
    liters NUMERIC(8, 3) NOT NULL,
    price_per_liter NUMERIC(7, 3) NOT NULL,
    total_cost NUMERIC(10, 2) NOT NULL,
    station_name VARCHAR(100),
    station_location VARCHAR(160),
    is_full_tank BOOLEAN NOT NULL DEFAULT TRUE,
    board_computer_avg NUMERIC(5, 2),
    reference_price NUMERIC(7, 3),
    savings_amount NUMERIC(10, 2),
    savings_type VARCHAR(24),
    computed_consumption NUMERIC(5, 2),
    client_mutation_id VARCHAR(64),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_fuel_client_mutation UNIQUE (client_mutation_id)
);
CREATE INDEX idx_fuel_vehicle_date ON fuel_logs (vehicle_id, fuel_date);
CREATE INDEX idx_fuel_vehicle_odo ON fuel_logs (vehicle_id, odometer);

CREATE TABLE maintenance_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(24) NOT NULL DEFAULT 'PREVENTIVE',
    interval_km INTEGER,
    interval_months INTEGER,
    baseline_odometer INTEGER,
    baseline_date DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rules_vehicle ON maintenance_rules (vehicle_id);

CREATE TABLE service_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    rule_id BIGINT REFERENCES maintenance_rules (id) ON DELETE SET NULL,
    service_date DATE NOT NULL,
    odometer INTEGER NOT NULL,
    category VARCHAR(24) NOT NULL,
    title VARCHAR(140) NOT NULL,
    total_cost NUMERIC(10, 2) NOT NULL DEFAULT 0,
    labor_cost NUMERIC(10, 2) NOT NULL DEFAULT 0,
    performed_by VARCHAR(16) NOT NULL,
    notes VARCHAR(2000),
    invoice_file_path VARCHAR(500),
    client_mutation_id VARCHAR(64),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_service_client_mutation UNIQUE (client_mutation_id),
    CONSTRAINT ck_service_category CHECK (category IN ('PREVENTIVE', 'CORRECTIVE', 'MODIFICATION', 'LEGAL')),
    CONSTRAINT ck_service_performed_by CHECK (performed_by IN ('DIY', 'WORKSHOP'))
);
CREATE INDEX idx_service_vehicle_date ON service_records (vehicle_id, service_date);

CREATE TABLE part_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_record_id BIGINT NOT NULL REFERENCES service_records (id) ON DELETE CASCADE,
    part_name VARCHAR(140) NOT NULL,
    oem_reference VARCHAR(80),
    brand VARCHAR(60),
    quantity NUMERIC(8, 2) NOT NULL DEFAULT 1,
    unit_price NUMERIC(10, 2) NOT NULL DEFAULT 0
);
CREATE INDEX idx_parts_record ON part_items (service_record_id);
